TOP = 5   # 비트맵 시작 행(16행 중)

def _pixels(ch, w, x0):
    """w폭 격자에 비트맵을 가운데 정렬해 [16][w] 픽셀(1=잉크)"""
    b = BMP[ch]
    bw = max(len(r) for r in b)
    off = x0 + (7 - bw) // 2
    g = [[0] * w for _ in range(16)]
    for y, r in enumerate(b):
        for x, c in enumerate(r):
            if c == "#":
                g[TOP + y][off + x] = 1
    return g

def _tile(g, tx, ty):
    out = bytearray()
    for y in range(8):
        for x in range(0, 8, 2):
            out.append(g[ty * 8 + y][tx * 8 + x] | g[ty * 8 + y][tx * 8 + x + 1] << 4)
    return bytes(out)

def font_glyph(ch):
    """K 폰트 형식 16x16(열 우선 4타일, 128B): 좌 F 4열, 잉크 4~12열(9px 폭), 우 F 3열"""
    p = _pixels(ch, 16, 4)
    g = [[0xF if (x < 4 or x > 12) else (0xE if p[y][x] else 0) for x in range(16)] for y in range(16)]
    return b"".join(_tile(g, tx, ty) for tx in (0, 1) for ty in (0, 1))

def key_tiles(ch):
    """자판 칸용 8x16(위/아래 타일 2장, 64B), 잉크 e/배경 0"""
    p = _pixels(ch, 8, 0)
    g = [[0xE if v else 0 for v in r] for r in p]
    return _tile(g, 0, 0) + _tile(g, 0, 1)

# ---- [한글] 버튼 (원본 [<-] 버튼 40x16을 바탕으로 화살표 지우고 글자) ----
BTN_ROM = 0x88E6300 - 0x08000000          # 언어 0 버튼 세트(かな 시작) 오프셋
BTN_BACK = (0x2E0 - 0x2C0) * 32           # [<-] 버튼 = 세트 내 오프셋
BTN_SETS = [0x88E6000 + i * 0x2000 - 0x08000000 for i in range(4)]
# [한글] 글자 비트맵 (image/hangul_btn_1_mono.png = 21x9 흑백 글자). 원본 버튼 박스는 그대로 두고
# 이 글자만 밝은색(idx E)으로 올린다. 버튼 안 배치: top행 3, left열 10 (가로·세로 중앙)
HANGUL_GLYPH = [
    "..##...##...#######..",
    "######.##.........##.",
    "..##...##..##########",
    "##..##.###...........",
    "..##...##...#######..",
    ".......##.........##.",
    ".##..........######..",
    ".##.........##.......",
    "..#######....#######.",
]
HANGUL_TOP, HANGUL_LEFT = 3, 10

def _btn_grid(raw):
    g = [[0] * 40 for _ in range(16)]
    for y in range(16):
        for x in range(40):
            if x < 32:
                t = (y // 8) * 4 + x // 8
                b = raw[t * 32 + (y % 8) * 4 + (x % 8) // 2]
            else:
                b = raw[256 + (y // 8) * 32 + (y % 8) * 4 + (x % 8) // 2]
            g[y][x] = (b >> (4 * (x & 1))) & 15
    return g

def _btn_raw(g):
    out = bytearray(320)
    for y in range(16):
        for x in range(40):
            if x < 32:
                o = ((y // 8) * 4 + x // 8) * 32 + (y % 8) * 4 + (x % 8) // 2
            else:
                o = 256 + (y // 8) * 32 + (y % 8) * 4 + (x % 8) // 2
            out[o] |= g[y][x] << (4 * (x & 1))
    return bytes(out)

def hangul_button(rom):
    o = BTN_ROM + BTN_BACK
    g = _btn_grid(rom[o:o + 320])
    for y in range(2, 13):          # 내부 배경으로 채워 [<-] 화살표 제거
        for x in range(8, 31):
            g[y][x] = g[y][8]
    for gy, row in enumerate(HANGUL_GLYPH):   # '한글' 글자만 밝은색으로 올림
        for gx, c in enumerate(row):
            if c == "#":
                g[HANGUL_TOP + gy][HANGUL_LEFT + gx] = 0xE
    return _btn_raw(g)

